//! # relations.rs: foreign keys, cascades, multi-column unique and pagination for SpacetimeDB
//!
//! SpacetimeDB has no foreign keys, no `ON DELETE`, and unique constraints on single columns
//! only. This drop-in adds them for writes that go through it, plus tools to find and fix data
//! that broke the rules before (or around) it.
//!
//! Copy this file to `src/relations.rs`, add `pub mod relations;` to `lib.rs`, and declare your
//! tables and references once, at the crate root:
//!
//! ```ignore
//! pub mod relations;
//!
//! relations! {
//!     tables {
//!         board: Board => id: u64,
//!         card: Card => id: u64,
//!         member: Member => id: u64,
//!         card_tag: CardTag => id: u64,
//!     }
//!     references {
//!         card.board_id -> board [cascade] via board_id,      // `via`: the btree index on the column
//!         card.parent_id -> card [cascade, nullable],         // Option<u64>, self-reference
//!         card.assignee -> member [set_null, nullable],
//!         card_tag.card_id -> card [cascade] via card_id,
//!     }
//!     unique {
//!         card_tag(card_id, tag) via by_card_tag,             // a multi-column btree index
//!     }
//! }
//! ```
//!
//! Then write through the generated wrappers instead of the raw table handles:
//!
//! ```ignore
//! #[spacetimedb::reducer]
//! fn add_card(ctx: &ReducerContext, board_id: u64, title: String) -> Result<(), String> {
//!     checked::card::insert(ctx, Card { id: 0, board_id, title, parent_id: None, assignee: None })?;
//!     Ok(())   // Err("card.board_id = 7: no such board") if the board doesn't exist
//! }
//!
//! #[spacetimedb::reducer]
//! fn delete_board(ctx: &ReducerContext, id: u64) -> Result<(), String> {
//!     checked::board::delete(ctx, &id)?;   // cards, their subtasks and tags go too; assignees untouched
//!     Ok(())
//! }
//! ```
//!
//! What you get:
//!
//! - **References** with `restrict`, `cascade` or `set_null` on delete, nullable (`Option`)
//!   columns and self-references. Checked inserts and updates refuse a missing parent.
//! - **Delete plans.** `checked::t::preview_delete` lists everything a delete would remove,
//!   unlink or be blocked by, so a UI can ask first. `delete` then applies the plan all or nothing.
//! - **Multi-column unique**, enforced by checked writes through a multi-column btree index.
//! - **Check and repair.** `relations_check` finds orphans and duplicates in existing data;
//!   `relations_repair` applies each reference's on-delete rule to the orphans. Admins only.
//! - **Pagination.** Keyset cursors for procedures (`page`, `cursor`), and subscribable pages:
//!   clients set a cursor with `relations_set_page`, your view reads it with `page_state`.
//! - **A public `relations_fk` / `relations_unique` table** describing the schema, for tools.
//!
//! Keys travel as hex of their BSATN encoding (the same as `spacetimedb-history`), so they're
//! byte-identical across Rust, C# and TypeScript.

use spacetimedb::sats::bsatn;
use spacetimedb::{Identity, ProcedureContext, ReducerContext, Table, ViewContext};
use std::collections::BTreeSet;

