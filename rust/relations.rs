/// Call from `init`: publishes the schema description and makes the caller (the publisher) an
/// admin. Safe to call again after a republish (`client_connected` or a migration reducer).
pub fn configure(ctx: &ReducerContext) {
    for r in ctx.db.relations_fk().iter() {
        ctx.db.relations_fk().id().delete(r.id);
    }
    for fk in crate::__relations_fks() {
        ctx.db.relations_fk().insert(RelationsFk {
            id: 0,
            child_table: fk.child.into(),
            child_column: fk.column.into(),
            parent_table: fk.parent.into(),
            on_delete: fk.on_delete,
            nullable: fk.nullable,
            indexed: fk.indexed,
        });
    }
    for r in ctx.db.relations_unique().iter() {
        ctx.db.relations_unique().id().delete(r.id);
    }
    for u in crate::__relations_uniques() {
        ctx.db.relations_unique().insert(RelationsUnique {
            id: 0,
            table_name: u.table.into(),
            columns: u.columns.iter().map(|c| c.to_string()).collect(),
        });
    }
    add_admin(ctx, ctx.sender());
}

pub fn add_admin(ctx: &ReducerContext, who: Identity) {
    if ctx.db.relations_admin().identity().find(who).is_none() {
        ctx.db
            .relations_admin()
            .insert(RelationsAdmin { identity: who });
    }
}

pub fn remove_admin(ctx: &ReducerContext, who: Identity) {
    ctx.db.relations_admin().identity().delete(who);
}

pub fn is_admin(ctx: &ReducerContext, who: Identity) -> bool {
    who == ctx.database_identity() || ctx.db.relations_admin().identity().find(who).is_some()
}

/// What deleting `table`/`key` (BSATN) would do. Reads only.
pub fn plan_delete(ctx: &ReducerContext, table: &str, key: &[u8]) -> Result<DeletePlan, String> {
    if !crate::__relations_exists(ctx, table, key)? {
        return Err(format!(
            "{table} {}: no such row",
            crate::__relations_show(table, key)
        ));
    }
    let fks = crate::__relations_fks();
    let mut seen: BTreeSet<(String, Vec<u8>)> = BTreeSet::new();
    seen.insert((table.to_string(), key.to_vec()));
    let mut order: Vec<(String, Vec<u8>)> = vec![(table.to_string(), key.to_vec())];
    let mut nulls: Vec<(String, &'static str, Vec<u8>)> = Vec::new();
    // (child table, column, child key, parent table, parent key)
    type Restrict = (String, &'static str, Vec<u8>, String, Vec<u8>);
    let mut restricts: Vec<Restrict> = Vec::new();
    // Breadth first, one level at a time, so a reference without an index is scanned once per
    // level rather than once per row.
    let mut frontier: Vec<(String, Vec<u8>)> = order.clone();
    while !frontier.is_empty() {
        let mut by_table: Vec<(String, Vec<Vec<u8>>)> = Vec::new();
        for (t, k) in frontier.drain(..) {
            match by_table.iter_mut().find(|(x, _)| *x == t) {
                Some((_, keys)) => keys.push(k),
                None => by_table.push((t, vec![k])),
            }
        }
        for (t, keys) in &by_table {
            for fk in fks.iter().filter(|fk| fk.parent == t) {
                for (pk, ck) in crate::__relations_children(ctx, fk.child, fk.column, keys)? {
                    match fk.on_delete {
                        CASCADE => {
                            if seen.insert((fk.child.to_string(), ck.clone())) {
                                order.push((fk.child.to_string(), ck.clone()));
                                frontier.push((fk.child.to_string(), ck));
                            }
                        }
                        SET_NULL => nulls.push((fk.child.to_string(), fk.column, ck)),
                        _ => restricts.push((fk.child.to_string(), fk.column, ck, t.clone(), pk)),
                    }
                }
            }
        }
    }
    // A child that's deleted anyway neither needs unlinking nor blocks anything.
    let doomed = |t: &str, k: &[u8]| seen.contains(&(t.to_string(), k.to_vec()));
    let mut plan = DeletePlan {
        deletes: order
            .iter()
            .map(|(t, k)| RowRef {
                table_name: t.clone(),
                key: hex(k),
            })
            .collect(),
        ..Default::default()
    };
    let mut nulled = BTreeSet::new();
    for (t, c, k) in nulls {
        if !doomed(&t, &k) && nulled.insert((t.clone(), c, k.clone())) {
            plan.nulls.push(NullRef {
                table_name: t,
                column: c.into(),
                key: hex(&k),
            });
        }
    }
    for (t, c, k, pt, pk) in restricts {
        if !doomed(&t, &k) {
            plan.blocked.push(Blocker {
                table_name: t,
                column: c.into(),
                key: hex(&k),
                parent_table: pt,
                parent_key: hex(&pk),
            });
        }
    }
    Ok(plan)
}

/// Delete `table`/`key` (BSATN) with every cascade, all or nothing. Refused (nothing changes)
/// if a `restrict` reference blocks it. Returns what was done.
pub fn delete(ctx: &ReducerContext, table: &str, key: &[u8]) -> Result<DeletePlan, String> {
    let plan = plan_delete(ctx, table, key)?;
    if let Some(b) = plan.blocked.first() {
        let more = match plan.blocked.len() {
            1 => String::new(),
            n => format!(" (and {} more)", n - 1),
        };
        let show = |t: &str, k: &str| {
            unhex(k)
                .map(|k| crate::__relations_show(t, &k))
                .unwrap_or_else(|_| k.to_string())
        };
        return Err(format!(
            "can't delete {table} {}: {} {} still references {} {} through {}{more}",
            crate::__relations_show(table, key),
            b.table_name,
            show(&b.table_name, &b.key),
            b.parent_table,
            show(&b.parent_table, &b.parent_key),
            b.column
        ));
    }
    apply(ctx, &plan)?;
    Ok(plan)
}

fn apply(ctx: &ReducerContext, plan: &DeletePlan) -> Result<(), String> {
    for n in &plan.nulls {
        crate::__relations_set_null(ctx, &n.table_name, &n.column, &unhex(&n.key)?)?;
    }
    // Leaves first.
    for d in plan.deletes.iter().rev() {
        crate::__relations_raw_delete(ctx, &d.table_name, &unhex(&d.key)?)?;
    }
    Ok(())
}

/// Every orphan and duplicate in the current data.
pub fn check(ctx: &ReducerContext) -> Result<Vec<Violation>, String> {
    let mut out = Vec::new();
    for fk in crate::__relations_fks() {
        for (ck, pk) in crate::__relations_orphans(ctx, fk.child, fk.column)? {
            out.push(Violation {
                kind: VIOLATION_ORPHAN,
                table_name: fk.child.into(),
                column: fk.column.into(),
                key: hex(&ck),
                parent_table: fk.parent.into(),
                parent_key: hex(&pk),
            });
        }
    }
    for u in crate::__relations_uniques() {
        for (k, first) in crate::__relations_duplicates(ctx, u.table, u.index)? {
            out.push(Violation {
                kind: VIOLATION_DUPLICATE,
                table_name: u.table.into(),
                column: u.columns.join(","),
                key: hex(&k),
                parent_table: u.table.into(),
                parent_key: hex(&first),
            });
        }
    }
    Ok(out)
}

/// Apply each reference's on-delete rule to its orphans: `cascade` deletes them (and their own
/// children), `set_null` unlinks them, `restrict` orphans and duplicates are reported only.
pub fn repair(ctx: &ReducerContext) -> Result<RepairReport, String> {
    let mut report = RepairReport::default();
    for v in check(ctx)? {
        if v.kind != VIOLATION_ORPHAN {
            report.unresolved.push(v);
            continue;
        }
        let fk = crate::__relations_fks()
            .iter()
            .find(|f| f.child == v.table_name && f.column == v.column)
            .ok_or("unknown reference")?;
        let key = unhex(&v.key)?;
        // An earlier cascade may have removed it already.
        if !crate::__relations_exists(ctx, &v.table_name, &key)? {
            continue;
        }
        match fk.on_delete {
            CASCADE => match plan_delete(ctx, &v.table_name, &key) {
                Ok(plan) if plan.blocked.is_empty() => {
                    apply(ctx, &plan)?;
                    report.deleted.extend(plan.deletes);
                    report.nulled.extend(plan.nulls);
                }
                _ => report.unresolved.push(v),
            },
            SET_NULL => {
                crate::__relations_set_null(ctx, &v.table_name, &v.column, &key)?;
                report.nulled.push(NullRef {
                    table_name: v.table_name,
                    column: v.column,
                    key: v.key,
                });
            }
            _ => report.unresolved.push(v),
        }
    }
    Ok(report)
}

// --- Pagination ------------------------------------------------------------

/// Clamp a requested page size: 0 means `DEFAULT_PAGE`, at most `MAX_PAGE`.
pub fn page_size(limit: u32) -> usize {
    match limit {
        0 => DEFAULT_PAGE as usize,
        n => n.min(MAX_PAGE) as usize,
    }
}

/// Take one page from `rows` (the rows after the cursor, e.g. an index range scan): the `limit`
/// rows with the smallest keys. `next` is the cursor of the last row returned, if more follow.
///
/// This reads the whole range: in SpacetimeDB 2.11 an index range scan inside a transaction
/// that inserted into the range returns those new rows first, out of key order, so stopping
/// early would pick the wrong rows (views are refreshed inside the writing transaction, so they
/// hit this on every insert). Keep ranges narrow, e.g. one list's cards. See FINDINGS.
pub fn page<T, K: spacetimedb::Serialize + Ord>(
    rows: impl Iterator<Item = T>,
    limit: u32,
    key: impl Fn(&T) -> K,
) -> Page<T> {
    let n = page_size(limit);
    let mut items: Vec<T> = rows.collect();
    let more = items.len() > n;
    if more {
        items.select_nth_unstable_by_key(n, |r| key(r));
        items.truncate(n);
    }
    items.sort_unstable_by_key(|r| key(r));
    let next = if more {
        items.last().map(|r| cursor_of(&key(r)))
    } else {
        None
    };
    Page { items, next }
}

/// The cursor for a key: hex of its BSATN.
pub fn cursor_of<K: spacetimedb::Serialize>(key: &K) -> String {
    hex(&encode(key))
}

/// Decode a cursor back into a key. `None` (or "") is the first page.
pub fn cursor<K: spacetimedb::DeserializeOwned>(c: Option<&str>) -> Result<Option<K>, String> {
    match c {
        None | Some("") => Ok(None),
        Some(s) => decode(&unhex(s)?).map(Some),
    }
}

/// Set `who`'s position in `list`. `relations_set_page` calls this for the sender.
pub fn set_page(
    ctx: &ReducerContext,
    who: Identity,
    list: &str,
    after: Option<String>,
    limit: u32,
) -> Result<(), String> {
    if list.len() > 256 {
        return Err("list name too long".into());
    }
    if let Some(a) = &after {
        unhex(a)?;
    }
    let limit = page_size(limit) as u32;
    match ctx
        .db
        .relations_page()
        .by_owner_list()
        .filter((who, list))
        .next()
    {
        Some(p) => {
            ctx.db
                .relations_page()
                .id()
                .update(RelationsPage { after, limit, ..p });
        }
        None => {
            ctx.db.relations_page().insert(RelationsPage {
                id: 0,
                owner: who,
                list: list.into(),
                after,
                limit,
            });
        }
    }
    Ok(())
}

/// Forget all of `who`'s page positions (e.g. from your `client_disconnected`).
pub fn clear_pages(ctx: &ReducerContext, who: Identity) {
    for p in ctx.db.relations_page().owner().filter(who) {
        ctx.db.relations_page().id().delete(p.id);
    }
}

/// The viewer's position in `list`, for a view. Before the client has set one: the first page
/// with `DEFAULT_PAGE` rows.
pub fn page_state(ctx: &ViewContext, list: &str) -> PageState {
    match ctx
        .db
        .relations_page()
        .by_owner_list()
        .filter((ctx.sender(), list))
        .next()
    {
        Some(p) => PageState {
            after: p.after,
            limit: p.limit,
        },
        None => PageState {
            after: None,
            limit: DEFAULT_PAGE,
        },
    }
}

/// Every list the viewer has a position in, for views over several lists.
pub fn page_states(ctx: &ViewContext) -> Vec<(String, PageState)> {
    ctx.db
        .relations_page()
        .owner()
        .filter(ctx.sender())
        .map(|p| {
            (
                p.list,
                PageState {
                    after: p.after,
                    limit: p.limit,
                },
            )
        })
        .collect()
}

// --- Encoding --------------------------------------------------------------

pub fn encode<T: spacetimedb::Serialize>(v: &T) -> Vec<u8> {
    bsatn::to_vec(v).expect("bsatn encoding can't fail")
}

pub fn decode<T: spacetimedb::DeserializeOwned>(bytes: &[u8]) -> Result<T, String> {
    bsatn::from_slice(bytes).map_err(|e| format!("bad key: {e}"))
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

pub fn unhex(s: &str) -> Result<Vec<u8>, String> {
    if !s.len().is_multiple_of(2) {
        return Err("bad hex key".into());
    }
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).map_err(|_| "bad hex key".to_string()))
        .collect()
}

