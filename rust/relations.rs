/// A row, by table and key (hex of the key's BSATN).
#[derive(spacetimedb::SpacetimeType, Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct RowRef {
    pub table_name: String,
    pub key: String,
}

/// A child row whose reference column would be set to `None`.
#[derive(spacetimedb::SpacetimeType, Clone, Debug, PartialEq)]
pub struct NullRef {
    pub table_name: String,
    pub column: String,
    pub key: String,
}

/// A child row that blocks the delete (`restrict`).
#[derive(spacetimedb::SpacetimeType, Clone, Debug, PartialEq)]
pub struct Blocker {
    pub table_name: String,
    pub column: String,
    pub key: String,
    pub parent_table: String,
    pub parent_key: String,
}

/// What deleting a row does. `deletes[0]` is the row itself; the rest are cascades.
#[derive(spacetimedb::SpacetimeType, Clone, Debug, Default, PartialEq)]
pub struct DeletePlan {
    pub deletes: Vec<RowRef>,
    pub nulls: Vec<NullRef>,
    pub blocked: Vec<Blocker>,
}

impl DeletePlan {
    /// "3 demo_list, 12 demo_card" style counts of the rows the plan deletes.
    pub fn counts(&self) -> Vec<(String, u32)> {
        let mut out: Vec<(String, u32)> = Vec::new();
        for d in &self.deletes {
            match out.iter_mut().find(|(t, _)| *t == d.table_name) {
                Some((_, n)) => *n += 1,
                None => out.push((d.table_name.clone(), 1)),
            }
        }
        out
    }
}

pub const VIOLATION_ORPHAN: u8 = 0;
pub const VIOLATION_DUPLICATE: u8 = 1;

/// A rule existing data breaks. Orphan: `table.column` points at a missing `parent_table`
/// row. Duplicate: another row has the same values in the unique `columns`.
#[derive(spacetimedb::SpacetimeType, Clone, Debug, PartialEq)]
pub struct Violation {
    pub kind: u8,
    pub table_name: String,
    /// The reference column (orphans), or the unique columns joined with "," (duplicates).
    pub column: String,
    pub key: String,
    pub parent_table: String,
    /// The missing parent's key (orphans), or the key of the row it duplicates.
    pub parent_key: String,
}

#[derive(spacetimedb::SpacetimeType, Clone, Debug, Default, PartialEq)]
pub struct RepairReport {
    pub deleted: Vec<RowRef>,
    pub nulled: Vec<NullRef>,
    /// What repair can't fix: orphans under `restrict` and duplicates (pick one yourself).
    pub unresolved: Vec<Violation>,
}

/// A page from `page()`: the rows, and the cursor for the next page (`None` at the end).
#[derive(Clone, Debug)]
pub struct Page<T> {
    pub items: Vec<T>,
    pub next: Option<String>,
}

/// A client's position in a paged list, read by your view with `page_state`.
#[derive(Clone, Debug)]
pub struct PageState {
    pub after: Option<String>,
    pub limit: u32,
}

pub const DEFAULT_PAGE: u32 = 50;
pub const MAX_PAGE: u32 = 500;

