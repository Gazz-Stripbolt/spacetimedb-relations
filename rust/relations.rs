/// Find orphans and duplicates. Admins only.
#[spacetimedb::procedure]
pub fn relations_check(ctx: &mut ProcedureContext) -> Result<Vec<Violation>, String> {
    ctx.with_tx(|tx| {
        if !is_admin(tx, tx.sender()) {
            return Err("relations_check is for admins".to_string());
        }
        check(tx)
    })
}

/// Apply on-delete rules to orphans, in one transaction. Admins only.
#[spacetimedb::procedure]
pub fn relations_repair(ctx: &mut ProcedureContext) -> Result<RepairReport, String> {
    ctx.try_with_tx(|tx| {
        if !is_admin(tx, tx.sender()) {
            return Err("relations_repair is for admins".to_string());
        }
        repair(tx)
    })
}

/// Move the caller to a page of `list` (`after` = the previous page's last key, as a cursor).
#[spacetimedb::reducer]
pub fn relations_set_page(
    ctx: &ReducerContext,
    list: String,
    after: Option<String>,
    limit: u32,
) -> Result<(), String> {
    set_page(ctx, ctx.sender(), &list, after, limit)
}

