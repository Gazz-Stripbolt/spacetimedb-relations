/// On delete of the parent: refuse while children exist.
pub const RESTRICT: u8 = 0;
/// On delete of the parent: delete the children too (recursively).
pub const CASCADE: u8 = 1;
/// On delete of the parent: set the child's column to `None`.
pub const SET_NULL: u8 = 2;

/// One declared reference (generated by `relations!`).
#[derive(Clone, Copy, Debug)]
pub struct FkInfo {
    pub child: &'static str,
    pub column: &'static str,
    pub parent: &'static str,
    pub on_delete: u8,
    pub nullable: bool,
    /// Children are found through a btree index (`via`) rather than a table scan.
    pub indexed: bool,
}

/// One declared multi-column unique constraint (generated by `relations!`).
#[derive(Clone, Copy, Debug)]
pub struct UniqueInfo {
    pub table: &'static str,
    pub columns: &'static [&'static str],
    pub index: &'static str,
}

