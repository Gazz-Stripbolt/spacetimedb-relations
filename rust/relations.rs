/// Declare your tables, references and multi-column unique constraints, once, at the crate root.
/// Generates `checked::<table>::{insert, update, upsert, delete, preview_delete}` and the glue the
/// library needs. See the module docs for the syntax.
///
/// - `tables`: `table: Row => pk: Key`, for every table that's a parent, a child or unique.
/// - `references`: `child.column -> parent [mode]` with mode `restrict`, `cascade` or `set_null`,
///   plus `, nullable` for `Option` columns (required by `set_null`). Add `via index` to find
///   children through a btree index on the column (non-nullable columns only, since `Option`
///   isn't index-filterable in SpacetimeDB 2.11); otherwise deletes scan the child table.
/// - `unique` (optional): `table(col_a, col_b, ...) via index`, where `index` is a btree index on
///   exactly those columns, in that order.
#[macro_export]
macro_rules! relations {
    // --- helpers ---
    (@mode restrict) => { $crate::relations::RESTRICT };
    (@mode cascade) => { $crate::relations::CASCADE };
    (@mode set_null) => { $crate::relations::SET_NULL };
    (@mode $other:ident) => { compile_error!(concat!("unknown on-delete mode `", stringify!($other), "`: use restrict, cascade or set_null")) };
    (@validate set_null, []) => { compile_error!("set_null needs a nullable (Option) column: write [set_null, nullable]") };
    (@validate $m:ident, [$($flag:ident)?]) => {};
    (@nullable []) => { false };
    (@nullable [nullable]) => { true };
    (@nullable [$other:ident]) => { compile_error!(concat!("unknown flag `", stringify!($other), "`: did you mean nullable?")) };
    (@indexed []) => { false };
    (@indexed [$idx:ident]) => { true };
    // The parent key a child row points at, as Option<&Key>.
    (@get $r:expr, $col:ident, []) => { Some(&$r.$col) };
    (@get $r:expr, $col:ident, [nullable]) => { $r.$col.as_ref() };
    (@null $row:ident, $col:ident, $child:ident, []) => {
        return Err(format!("{}.{} isn't nullable", stringify!($child), stringify!($col)))
    };
    (@null $row:ident, $col:ident, $child:ident, [nullable]) => { $row.$col = None; };
    // (parent key, child key) for every child of any of the parents: `$keys` typed, `$raw` BSATN.
    (@children $ctx:ident, $child:ident, $col:ident, $keys:ident, $raw:ident, [], [$idx:ident]) => {{
        let mut out = Vec::new();
        for (k, kb) in $keys.iter().zip($raw.iter()) {
            for r in $ctx.db.$child().$idx().filter(k) {
                out.push((kb.clone(), $crate::relations::encode(checked::$child::key_of(&r))));
            }
        }
        out
    }};
    (@children $ctx:ident, $child:ident, $col:ident, $keys:ident, $raw:ident, [nullable], [$idx:ident]) => {
        compile_error!("`via` needs a non-nullable column: Option columns can't be index-filtered, so leave `via` off")
    };
    (@children $ctx:ident, $child:ident, $col:ident, $keys:ident, $raw:ident, [$($flag:ident)?], []) => {{
        let _ = &$keys;
        let wanted: std::collections::BTreeSet<&[u8]> = $raw.iter().map(|k| k.as_slice()).collect();
        let mut out = Vec::new();
        for r in $ctx.db.$child().iter() {
            if let Some(k) = $crate::relations!(@get r, $col, [$($flag)?]) {
                let kb = $crate::relations::encode(k);
                if wanted.contains(kb.as_slice()) {
                    out.push((kb, $crate::relations::encode(checked::$child::key_of(&r))));
                }
            }
        }
        out
    }};

    // --- entry point ---
    (
        tables { $($table:ident : $row:ty => $pk:ident : $key:ty),* $(,)? }
        references { $($child:ident . $col:ident -> $parent:ident [$mode:ident $(, $flag:ident)?] $(via $idx:ident)?),* $(,)? }
        $(unique { $($ut:ident ( $($uc:ident),+ ) via $uidx:ident),* $(,)? })?
    ) => {
        $( $crate::relations!(@validate $mode, [$($flag)?]); )*

        /// Checked writes for each table declared in `relations!`.
        pub mod checked {
            $(
                #[allow(non_snake_case, dead_code)]
                pub mod $table {
                    #[allow(unused_imports)]
                    use super::super::*;
                    use spacetimedb::{ReducerContext, Table};

                    pub type Row = $row;
                    pub type Key = $key;
                    pub const NAME: &str = stringify!($table);

                    pub fn key_of(row: &Row) -> &Key { &row.$pk }

                    pub fn exists(ctx: &ReducerContext, key: &Key) -> bool {
                        ctx.db.$table().$pk().find(key).is_some()
                    }

                    /// Insert after checking references and unique constraints. Returns the
                    /// inserted row (with auto-inc values filled in).
                    pub fn insert(ctx: &ReducerContext, row: Row) -> Result<Row, String> {
                        $crate::__relations_check_refs(ctx, &row)?;
                        $crate::__relations_check_unique(ctx, &row, false)?;
                        ctx.db.$table().try_insert(row).map_err(|e| format!("{}: {}", NAME, e))
                    }

                    /// Update by primary key after checking references and unique constraints.
                    pub fn update(ctx: &ReducerContext, row: Row) -> Result<Row, String> {
                        if ctx.db.$table().$pk().find(&row.$pk).is_none() {
                            return Err(format!("{} {:?}: no such row", NAME, row.$pk));
                        }
                        $crate::__relations_check_refs(ctx, &row)?;
                        $crate::__relations_check_unique(ctx, &row, true)?;
                        Ok(ctx.db.$table().$pk().update(row))
                    }

                    /// Insert or update by primary key, checked.
                    pub fn upsert(ctx: &ReducerContext, row: Row) -> Result<Row, String> {
                        if ctx.db.$table().$pk().find(&row.$pk).is_some() { update(ctx, row) } else { insert(ctx, row) }
                    }

                    /// Delete with cascades, all or nothing. Refused if a `restrict` reference blocks it.
                    pub fn delete(ctx: &ReducerContext, key: &Key) -> Result<$crate::relations::DeletePlan, String> {
                        $crate::relations::delete(ctx, NAME, &$crate::relations::encode(key))
                    }

                    /// What `delete` would do, without doing it.
                    pub fn preview_delete(ctx: &ReducerContext, key: &Key) -> Result<$crate::relations::DeletePlan, String> {
                        $crate::relations::plan_delete(ctx, NAME, &$crate::relations::encode(key))
                    }

                    pub(crate) fn find_bytes(ctx: &ReducerContext, key: &[u8]) -> Result<Option<Row>, String> {
                        let key: Key = $crate::relations::decode(key)?;
                        Ok(ctx.db.$table().$pk().find(&key))
                    }

                    pub(crate) fn raw_update(ctx: &ReducerContext, row: Row) {
                        ctx.db.$table().$pk().update(row);
                    }

                    pub(crate) fn raw_delete(ctx: &ReducerContext, key: &[u8]) -> Result<bool, String> {
                        let key: Key = $crate::relations::decode(key)?;
                        Ok(ctx.db.$table().$pk().delete(&key))
                    }
                }
            )*
        }

        #[doc(hidden)]
        pub fn __relations_fks() -> &'static [$crate::relations::FkInfo] {
            &[$(
                $crate::relations::FkInfo {
                    child: stringify!($child),
                    column: stringify!($col),
                    parent: stringify!($parent),
                    on_delete: $crate::relations!(@mode $mode),
                    nullable: $crate::relations!(@nullable [$($flag)?]),
                    indexed: $crate::relations!(@indexed [$($idx)?]),
                },
            )*]
        }

        #[doc(hidden)]
        pub fn __relations_uniques() -> &'static [$crate::relations::UniqueInfo] {
            &[$($(
                $crate::relations::UniqueInfo {
                    table: stringify!($ut),
                    columns: &[$(stringify!($uc)),+],
                    index: stringify!($uidx),
                },
            )*)?]
        }

        #[doc(hidden)]
        pub fn __relations_exists(ctx: &spacetimedb::ReducerContext, table: &str, key: &[u8]) -> Result<bool, String> {
            $( if table == stringify!($table) { return Ok(checked::$table::find_bytes(ctx, key)?.is_some()); } )*
            Err(format!("{table} isn't declared in relations!"))
        }

        /// A key, for error messages: `{:?}` of the decoded key (hex if it doesn't decode).
        #[doc(hidden)]
        pub fn __relations_show(table: &str, key: &[u8]) -> String {
            $( if table == stringify!($table) {
                return match $crate::relations::decode::<checked::$table::Key>(key) {
                    Ok(k) => format!("{:?}", k),
                    Err(_) => $crate::relations::hex(key),
                };
            } )*
            $crate::relations::hex(key)
        }

        #[doc(hidden)]
        pub fn __relations_raw_delete(ctx: &spacetimedb::ReducerContext, table: &str, key: &[u8]) -> Result<bool, String> {
            $( if table == stringify!($table) { return checked::$table::raw_delete(ctx, key); } )*
            Err(format!("{table} isn't declared in relations!"))
        }

        #[doc(hidden)]
        #[allow(unused_variables)]
        /// (parent key, child key) for the children of `parent_keys` through `child.column`.
        pub fn __relations_children(ctx: &spacetimedb::ReducerContext, child: &str, column: &str, parent_keys: &[Vec<u8>]) -> Result<Vec<(Vec<u8>, Vec<u8>)>, String> {
            $(
                if child == stringify!($child) && column == stringify!($col) {
                    let keys = parent_keys.iter().map(|k| $crate::relations::decode::<checked::$parent::Key>(k)).collect::<Result<Vec<_>, _>>()?;
                    return Ok($crate::relations!(@children ctx, $child, $col, keys, parent_keys, [$($flag)?], [$($idx)?]));
                }
            )*
            Err(format!("{child}.{column} isn't a declared reference"))
        }

        #[doc(hidden)]
        #[allow(unused_variables, unused_mut, unreachable_code)]
        pub fn __relations_set_null(ctx: &spacetimedb::ReducerContext, child: &str, column: &str, key: &[u8]) -> Result<(), String> {
            $(
                if child == stringify!($child) && column == stringify!($col) {
                    let Some(mut row) = checked::$child::find_bytes(ctx, key)? else { return Ok(()) };
                    $crate::relations!(@null row, $col, $child, [$($flag)?]);
                    checked::$child::raw_update(ctx, row);
                    return Ok(());
                }
            )*
            Err(format!("{child}.{column} isn't a declared reference"))
        }

        #[doc(hidden)]
        #[allow(unused_variables)]
        pub fn __relations_orphans(ctx: &spacetimedb::ReducerContext, child: &str, column: &str) -> Result<Vec<(Vec<u8>, Vec<u8>)>, String> {
            use spacetimedb::Table;
            $(
                if child == stringify!($child) && column == stringify!($col) {
                    return Ok(ctx.db.$child().iter().filter_map(|r| {
                        let k = $crate::relations!(@get r, $col, [$($flag)?])?;
                        if checked::$parent::exists(ctx, k) { return None; }
                        Some(($crate::relations::encode(checked::$child::key_of(&r)), $crate::relations::encode(k)))
                    }).collect());
                }
            )*
            Err(format!("{child}.{column} isn't a declared reference"))
        }

        /// (duplicate key, key of the first row with the same values), for each extra row.
        #[doc(hidden)]
        #[allow(unused_variables)]
        pub fn __relations_duplicates(ctx: &spacetimedb::ReducerContext, table: &str, index: &str) -> Result<Vec<(Vec<u8>, Vec<u8>)>, String> {
            #[allow(unused_imports)]
            use spacetimedb::Table;
            $($(
                if table == stringify!($ut) && index == stringify!($uidx) {
                    let mut out = Vec::new();
                    let mut seen = std::collections::BTreeSet::new();
                    for r in ctx.db.$ut().iter() {
                        // The row with the smallest key keeps the values; the others are duplicates.
                        let first = ctx.db.$ut().$uidx().filter(($(&r.$uc),+ ,))
                            .map(|o| checked::$ut::key_of(&o).clone())
                            .min()
                            .map(|k| $crate::relations::encode(&k))
                            .expect("the row itself matches");
                        let mine = $crate::relations::encode(checked::$ut::key_of(&r));
                        if first != mine && seen.insert(mine.clone()) {
                            out.push((mine, first));
                        }
                    }
                    return Ok(out);
                }
            )*)?
            Err(format!("{table}.{index} isn't a declared unique constraint"))
        }

        #[doc(hidden)]
        #[allow(unused_variables)]
        pub fn __relations_check_refs<R: 'static>(ctx: &spacetimedb::ReducerContext, row: &R) -> Result<(), String> {
            let any = row as &dyn std::any::Any;
            $(
                if let Some(r) = any.downcast_ref::<checked::$child::Row>() {
                    if let Some(k) = $crate::relations!(@get r, $col, [$($flag)?]) {
                        if !checked::$parent::exists(ctx, k) {
                            return Err(format!("{}.{} = {:?}: no such {}", stringify!($child), stringify!($col), k, stringify!($parent)));
                        }
                    }
                }
            )*
            Ok(())
        }

        #[doc(hidden)]
        #[allow(unused_variables)]
        pub fn __relations_check_unique<R: 'static>(ctx: &spacetimedb::ReducerContext, row: &R, updating: bool) -> Result<(), String> {
            let any = row as &dyn std::any::Any;
            $($(
                if let Some(r) = any.downcast_ref::<checked::$ut::Row>() {
                    let clash = ctx.db.$ut().$uidx().filter(($(&r.$uc),+ ,))
                        .any(|o| !updating || checked::$ut::key_of(&o) != checked::$ut::key_of(r));
                    if clash {
                        return Err(format!(
                            "{}: another row already has this ({})",
                            stringify!($ut),
                            stringify!($($uc),+)
                        ));
                    }
                }
            )*)?
            Ok(())
        }
    };
}
