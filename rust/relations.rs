/// The declared references, for clients and tools. Rewritten by `configure`.
#[spacetimedb::table(accessor = relations_fk, public)]
#[derive(Clone, Debug)]
pub struct RelationsFk {
    #[primary_key]
    #[auto_inc]
    pub id: u64,
    pub child_table: String,
    pub child_column: String,
    pub parent_table: String,
    pub on_delete: u8,
    pub nullable: bool,
    pub indexed: bool,
}

/// The declared multi-column unique constraints. Rewritten by `configure`.
#[spacetimedb::table(accessor = relations_unique, public)]
#[derive(Clone, Debug)]
pub struct RelationsUnique {
    #[primary_key]
    #[auto_inc]
    pub id: u64,
    pub table_name: String,
    pub columns: Vec<String>,
}

/// Who may run `relations_check` / `relations_repair` (the publisher, after `configure`).
#[spacetimedb::table(accessor = relations_admin)]
pub struct RelationsAdmin {
    #[primary_key]
    pub identity: Identity,
}

/// Each client's position in each paged list (see `page_state`).
#[spacetimedb::table(
    accessor = relations_page,
    index(accessor = by_owner_list, btree(columns = [owner, list]))
)]
#[derive(Clone, Debug)]
pub struct RelationsPage {
    #[primary_key]
    #[auto_inc]
    pub id: u64,
    #[index(btree)]
    pub owner: Identity,
    pub list: String,
    /// Hex BSATN of the last key of the previous page. `None`: the first page.
    pub after: Option<String>,
    pub limit: u32,
}

